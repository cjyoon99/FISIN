let defectTrash = [];
async function loadDefectEntries(){
  const all = await storageGetMany('defect:', true);
  if(backendOnline){
    // [v65] 서버에 아직 안 올라간(동기화 대기중) 로컬 항목은 유실되지 않도록 id 기준으로 합친다.
    const serverIds = new Set(all.map(e=>e.id));
    const stillPending = [...defectEntries, ...defectTrash].filter(e=>e.id && !serverIds.has(e.id));
    const merged = [...all, ...stillPending];
    defectEntries = merged.filter(e=>!e.deleted).sort((a,b)=>a.ts-b.ts);
    defectTrash = merged.filter(e=>e.deleted).sort((a,b)=>(a._deletedAt||0)-(b._deletedAt||0));
  } else {
    defectEntries = lsCacheGet('defects') || defectEntries; // [v65] 오프라인 — 캐시/현재 메모리 유지(비우지 않음)
    defectTrash = lsCacheGet('defectTrash') || defectTrash;
  }
  renderDefectEntries();
}
