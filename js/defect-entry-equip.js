// 펌프류와 동일하게 "그 자체가 실제 설비명"으로 취급 — 계단/복도/거실/피난구유도등별
// EQUIP_DEFECT_MAP·NFTC 매핑이 그대로 적용되게 한다.
const PROMOTE_SUB_AS_EQUIP = NESTED_PUMP_EQUIP.concat(Object.values(EQUIP_SIMILAR_SUB).flat());
// 불량예시/NFTC/저장 시 "실제 설비명"으로 취급할 대상을 계산.
// 2단계가 펌프류(NESTED_PUMP_EQUIP)나 유사설비 후보(PROMOTE_SUB_AS_EQUIP)면 그 이름 자체가 설비명이 되고
// (상위 1단계는 "소속" 역할만), 3단계(구성부품)를 골랐으면 그게 세부항목이 된다. 아니면 기존처럼 1단계+2단계 그대로 사용.
function getEffectiveEquip(){
  if(defectState.equipSub && PROMOTE_SUB_AS_EQUIP.includes(defectState.equipSub)){
    return { name: defectState.equipSub, sub: defectState.equipSubSub, parent: defectState.equipPrimary };
  }
  return { name: defectState.equipPrimary, sub: defectState.equipSub, parent: null };
}

function syncEquipToDefectContent(){
  const eff = getEffectiveEquip();
  const newPrefix = eff.name ? eff.name + (eff.sub ? ' ' + eff.sub : '') : '';
  const box = $('defectContent');
  let rest = box.value;
  if(currentEquipPrefix && rest.startsWith(currentEquipPrefix)){
    rest = rest.slice(currentEquipPrefix.length).replace(/^\s*·?\s*/, '');
  }
  box.value = newPrefix ? (rest ? newPrefix + ' ' + rest : newPrefix) : rest;
  currentEquipPrefix = newPrefix;
}

