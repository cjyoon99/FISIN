// "새 일정 추가"·"직접 입력해서 시작" 어디서든 대상물 화면을 열기 전에 이 함수를 먼저 불러,
// 이름이 대상물 마스터 DB에 있으면 기준정보·설비목록·동층구조를 자동으로 채운다.
// 이미 값이 있으면(7개 대상물의 수작업 큐레이션본 등) 덮어쓰지 않아 기존 정밀 데이터를 보존한다.
function ensureMasterDataFor(name){
  // [v41] 대상물 마스터 데이터 파일(<script src>)이 어떤 이유로든 로드되지 않았을 때,
  // 여기서 앱 전체가 멈추지 않고 "DB 연동 없이" 이전처럼 동작하도록 안전하게 빠져나감.
  if(typeof BUILDINGS_MASTER === 'undefined' || !BUILDINGS_MASTER) return false;
  // [v54] 정확히 일치하는 키가 없으면(예: 일정명 "여진모건물" vs DB키 "여진모 건물") 공백 제거 정규화로 재시도
  const entry = findMasterEntryByName(name);
  if(!entry) return false;
  const fresh = masterEntryToProfileFields(entry);
  if(!BUILDING_PROFILES[name]){
    BUILDING_PROFILES[name] = fresh;
  } else {
    // [v58] 예전 버전 변환기로 만들어진 프로필(예: 화정초 등 7개 손큐레이션 대상물)은
    // "이미 있으니 통째로 스킵"하면 새로 추가된 필드(건축허가일·세대수·최근교육이수일·
    // 전자우편 등)가 영영 안 채워진다. 기존 값은 절대 안 건드리되, 거기 "없는" 필드만
    // 마스터DB(V08)에서 채워 넣는다.
    const cur = BUILDING_PROFILES[name];
    for(const k in fresh){
      if(k === 'spec') continue; // spec은 아래서 별도 규칙
      if(cur[k]===undefined || cur[k]===null || cur[k]==='') cur[k] = fresh[k];
    }
    // spec(기기사양): 마스터DB(V08, Sheet4 정식 매핑+설치위치 텍스트 정제)가 기존
    // 손큐레이션보다 항목이 더 많으면(=더 완전하면) 통째로 교체한다.
    const specItemCount = s => Object.values(s||{}).reduce((n,mids)=>
      n + Object.values(mids||{}).reduce((m,items)=>m+((items&&items.length)||0), 0), 0);
    if(specItemCount(fresh.spec) > specItemCount(cur.spec)) cur.spec = fresh.spec;
  }
  if(!EQUIP_DB[name]) EQUIP_DB[name] = masterEquipToEquipDB(entry.equip);
  if(!BUILDING_STRUCTURE[name]) BUILDING_STRUCTURE[name] = masterWingsToStructure(entry.wings);
  return true;
}

