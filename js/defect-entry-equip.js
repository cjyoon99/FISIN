// [v27] 동 select · 층 select 2개를 각각 클릭하던 것을 하나의 통합 드롭박스(locCombinedSelect)로 바꿈.
// wingSelect/floorSelect는 화면에서 숨겨진 채 "실제 값을 들고 있는 저장소" 역할만 하고,
// 기존 저장 로직(불량내역 저장 등)은 그대로 이 두 select의 .value를 읽으므로 수정 범위를 최소화함.
function renderLocationSelectors(){
  const struct = BUILDING_STRUCTURE[currentBuilding] || BUILDING_STRUCTURE['_default'];
  const wingSel = $('wingSelect'), floorSel = $('floorSelect');
  if(struct.wings.length){
    $('wingEditBtn').style.display = '';
    wingSel.innerHTML = struct.wings.map(w=>`<option value="${w}">${w}</option>`).join('');
  } else {
    $('wingEditBtn').style.display = 'none';
    wingSel.innerHTML = '';
  }
  floorSel.innerHTML = struct.floors.map(f=>`<option value="${f}">${f}</option>`).join('');
  // [v19] 목록 맨 앞 항목이 아니라, 이 대상물에서 마지막에 "기본값으로" 저장해둔
  // 동/층이 있으면 그걸 화면에 미리 선택해둔다(예: 꽃바위유치원의 기본 층이 항상 B3로
  // 뜨던 문제 — 목록 순서상 B3가 맨 앞이라 매번 다시 골라야 했던 것).
  const def = uiPrefs.defaultLocation[currentBuilding];
  if(def){
    if(def.wing && struct.wings.includes(def.wing)) wingSel.value = def.wing;
    if(def.floor && struct.floors.includes(def.floor)) floorSel.value = def.floor;
  }
  renderCombinedLocationSelect();
}
// 동×층 조합을 하나의 드롭박스 옵션으로 만든다 (동이 없는 대상물은 층만 나열)
function renderCombinedLocationSelect(){
  const struct = BUILDING_STRUCTURE[currentBuilding] || BUILDING_STRUCTURE['_default'];
  const combo = $('locCombinedSelect');
  const wings = struct.wings.length ? struct.wings : [''];
  const opts = [];
  wings.forEach(w=>{
    // [v42] 동마다 실제 층수가 다를 수 있음(예: 본관동 4층, 강당동 2층).
    // struct.floorsByWing에 그 동의 실제 층 목록이 있으면 그것만 쓰고, 없으면(기존 방식)
    // 전체 공통 floors를 그대로 써서 예전 대상물은 지금까지와 똑같이 동작한다.
    const floorsForWing = (struct.floorsByWing && struct.floorsByWing[w]) ? struct.floorsByWing[w] : struct.floors;
    floorsForWing.forEach(f=>{
      const label = w ? `${w} ${f}` : f;
      opts.push(`<option value="${w}|${f}">${label}</option>`);
    });
  });
  combo.innerHTML = opts.join('');
  syncCombinedLocationValue();
}
// 숨겨진 wingSelect/floorSelect의 현재 값을 통합 드롭박스에 반영
function syncCombinedLocationValue(){
  const w = $('wingSelect').options.length ? $('wingSelect').value : '';
  const f = $('floorSelect').value;
  $('locCombinedSelect').value = `${w}|${f}`;
}
// [v20 신규] 목록에 있는 동/층 이름 자체가 틀렸을 때(오탈자·오류) 고치는 기능.
// "기본값으로 저장"과는 다르다 — 그건 목록 중 뭘 기본으로 고를지 정하는 것이고,
// 이건 목록에 있는 값 자체(예: 'B3')를 다른 값('F3')으로 영구적으로 바꾸는 것이다.
function renameLocationValue(kind, oldVal){
  if(!currentBuilding){ showToast('대상물을 먼저 선택해주세요'); return; }
  if(!oldVal){ showToast('수정할 값이 없습니다'); return; }
  const newVal = prompt(`"${oldVal}"을(를) 무엇으로 고칠까요?`, oldVal);
  if(newVal==null) return; // 취소
  const nv = newVal.trim();
  if(!nv || nv===oldVal){ return; }
  const struct = BUILDING_STRUCTURE[currentBuilding];
  if(!struct) return;
  const arr = kind==='wing' ? struct.wings : struct.floors;
  const idx = arr.indexOf(oldVal);
  if(idx!==-1) arr[idx] = nv;
  // 기본값으로 저장해둔 값이 옛 이름이었다면 같이 바꿔줌
  const def = uiPrefs.defaultLocation[currentBuilding];
  if(def){ if(kind==='wing' && def.wing===oldVal) def.wing=nv; if(kind==='floor' && def.floor===oldVal) def.floor=nv; }
  // 팀 공유 저장 - 다음에 이 대상물을 열 때(팀원 포함) 고쳐진 이름으로 보이도록 영구 저장
  const renames = uiPrefs.locationRenames[currentBuilding] || (uiPrefs.locationRenames[currentBuilding] = {wings:{}, floors:{}});
  renames[kind==='wing'?'wings':'floors'][oldVal] = nv;
  saveUiPrefsDebounced();
  renderLocationSelectors();
  if(kind==='wing') $('wingSelect').value = nv; else $('floorSelect').value = nv;
  syncCombinedLocationValue();
  showToast(`"${oldVal}" → "${nv}"로 수정했습니다 (팀원과 공유되고, 다음에도 이 이름으로 나옵니다)`);
}
