let _masterNormIndex = null;
function getMasterNormIndex(){
  if(_masterNormIndex) return _masterNormIndex;
  _masterNormIndex = {};
  if(typeof BUILDINGS_MASTER !== 'undefined' && BUILDINGS_MASTER && BUILDINGS_MASTER.data){
    Object.keys(BUILDINGS_MASTER.data).forEach(key=>{
      const norm = normalizeBuildingName(key);
      if(!_masterNormIndex[norm]) _masterNormIndex[norm] = [];
      _masterNormIndex[norm].push(key);
    });
  }
  return _masterNormIndex;
}
// [v55] 별칭(약칭) 정규화 인덱스 — BUILDINGS_MASTER.aliases = {"약칭":"공식대상물명", ...} 형태.
// 약칭 쪽도 공백 차이가 있을 수 있으므로 정규화해서 인덱싱한다.
let _aliasNormIndex = null;
function getAliasNormIndex(){
  if(_aliasNormIndex) return _aliasNormIndex;
  _aliasNormIndex = {};
  if(typeof BUILDINGS_MASTER !== 'undefined' && BUILDINGS_MASTER && BUILDINGS_MASTER.aliases){
    Object.keys(BUILDINGS_MASTER.aliases).forEach(alias=>{
      const norm = normalizeBuildingName(alias);
      _aliasNormIndex[norm] = BUILDINGS_MASTER.aliases[alias]; // 공식 대상물명(마스터DB 키)
    });
  }
  return _aliasNormIndex;
}
function findMasterEntryByName(name){
  if(typeof BUILDINGS_MASTER === 'undefined' || !BUILDINGS_MASTER || !BUILDINGS_MASTER.data) return null;
  // 1) 완전 일치
  if(BUILDINGS_MASTER.data[name]) return BUILDINGS_MASTER.data[name];
  const norm = normalizeBuildingName(name);
  // 2) 공백만 다른 경우 (예: "여진모건물" vs "여진모 건물")
  const candidates = getMasterNormIndex()[norm];
  if(candidates && candidates.length === 1) return BUILDINGS_MASTER.data[candidates[0]];
  // 3) 약칭 테이블 (예: "강남교육청" → "강남교육지원청")
  const aliasTarget = getAliasNormIndex()[norm];
  if(aliasTarget){
    if(BUILDINGS_MASTER.data[aliasTarget]) return BUILDINGS_MASTER.data[aliasTarget];
    const aliasNorm = normalizeBuildingName(aliasTarget);
    const aliasCandidates = getMasterNormIndex()[aliasNorm];
    if(aliasCandidates && aliasCandidates.length === 1) return BUILDINGS_MASTER.data[aliasCandidates[0]];
  }
  return null; // 매칭 없음 또는 충돌 — 안전하게 매칭하지 않고 넘어간다
}
