// 설비명(+부속설비)에 맞는 불량내용 후보 목록을 반환. 매핑에 없으면 공통 DEFECT_TAGS로 폴백
function getDefectTagsFor(equipName, equipSub){
  if(equipName){
    const subKey = equipSub ? (equipName + ' ' + equipSub) : null;
    if(subKey && EQUIP_DEFECT_MAP[subKey]) return EQUIP_DEFECT_MAP[subKey];
    if(EQUIP_DEFECT_MAP[equipName]) return EQUIP_DEFECT_MAP[equipName];
    // 세부항목을 아직 고르지 않았고, 이 설비명 단독 키도 EQUIP_DEFECT_MAP에 없는 경우(부속설비별로만 등록된 설비):
    // 그 설비의 세부항목 조합 키들을 모두 모아 즉시 보여준다 — 세부항목을 골라야만 특화된 목록이 뜨는 지연을 없앰.
    if(!equipSub){
      const prefix = equipName + ' ';
      const merged = [];
      Object.keys(EQUIP_DEFECT_MAP).forEach(k=>{
        if(k.indexOf(prefix)===0){
          EQUIP_DEFECT_MAP[k].forEach(tag=>{ if(merged.indexOf(tag)===-1) merged.push(tag); });
        }
      });
      if(merged.length) return merged;
    }
  }
  return DEFECT_TAGS;
}
